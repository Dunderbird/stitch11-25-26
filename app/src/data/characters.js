const rankSteps = [
  { limit: 5, title: "GABAGOOL NOVICE" },
  { limit: 15, title: "CANNELLONI APPRENTICE" },
  { limit: 30, title: "AL DENTE GLADIATOR" },
  { limit: 60, title: "MARINARA CAPO" },
  { limit: 100, title: "ESPRESSO GODFATHER" },
]

export function calculateRank(value) {
  const step = rankSteps.find((rank) => value < rank.limit)

  if (!step) {
    return { title: "SUPREME BRAINROT NONNA", nextReq: null, progress: 100 }
  }

  return {
    title: step.title,
    nextReq: step.limit,
    progress: Math.min(100, (value / step.limit) * 100),
  }
}
